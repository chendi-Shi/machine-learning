import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
data=pd.read_excel(r"C:\Users\师晨迪\Documents\机器学习\机器学习\anomoly detection.xlsx")
fig1=plt.figure()
plt.scatter(data.loc[:,'x1'],data.loc[:,'x2'])
plt.title('Data')
plt.xlabel('x1')
plt.ylabel('x2')
plt.show()
#define x1 and x2
x1=data.loc[:,'x1']
x2=data.loc[:,'x2']
fig2=plt.figure()
plt.subplot(121)
plt.hist(x1,bins=100)
plt.title('x1 distribution')
plt.xlabel('x1')
plt.ylabel('counts')
plt.subplot(122)
plt.hist(x2,bins=100)
plt.title('x2 distribution')
plt.xlabel('x2')
plt.ylabel('counts')
plt.show()
#calculate the mean and sigma of x1 and x2
print(data['x1'].describe(),data['x2'].describe())
x1_mean=data['x1'].mean()
x2_mean=data['x2'].mean()
x1_sigma=data['x1'].std()
x2_sigma=data['x2'].std()
#calculate the gaussian distriution p(x)
from scipy.stats import norm
x1_range=np.linspace(0,20,300)
x1_normal=norm.pdf(x1_range,x1_mean,x1_sigma)
print(x1_normal)
#visualize the p(x)
fig3=plt.figure()
plt.plot(x1_range,x1_normal)
plt.title('normal p(x1)')
plt.show()
x2_range=np.linspace(0,20,300)
x2_normal=norm.pdf(x2_range,x2_mean,x2_sigma)
print(x2_normal)
#visualize the p(x)
fig4=plt.figure()
plt.plot(x2_range,x2_normal)
plt.title('normal p(x2)')
plt.show()
from sklearn.covariance import EllipticEnvelope
ad_model=EllipticEnvelope()
ad_model.fit(data)
#make prediction
y_pred=ad_model.predict(data)
print(y_pred)
y_pred_series=pd.Series(y_pred)
print(y_pred_series.value_counts())
#visualize the result
fig5=plt.figure()
origin_data=plt.scatter(data.loc[:,'x1'],data.loc[:,'x2'],marker='x')
anomaly_data=plt.scatter(data.loc[:,'x1'][y_pred==-1],data.loc[:,'x2'][y_pred==-1],marker='o')
plt.title('anomaly detection result')
plt.xlabel('x1')
plt.ylabel('x2')
plt.legend((origin_data,anomaly_data),('origin','anomaly'))
plt.show()
ad_model=EllipticEnvelope(contamination=0.1)
